#pragma once

#include "Containers/Map.h"
#include "Containers/UnrealString.h"
#include "Templates/SharedPointer.h"

class UHoudiniOutput;
class UDataAsset;
class UClass;
class FProperty;
class FString;
class FJsonObject;
class FJsonValue;
struct FHoudiniGeoPartObject;
struct FHoudiniPackageParams;

struct HOUDINIENGINE_API FHoudiniDataAssetTranslator
{
	// Creates a Data Asset from the class and either JSON dictionary values or individual point attributes
	// generated by a Data Asset input.
	static bool BuildDataAsset(
		const FHoudiniGeoPartObject& HGPO,
		UHoudiniOutput* CurOutput,
		const FHoudiniPackageParams& PackageParams);

private:
	static UClass* LoadDataAssetClass(const FString& ClassPath);

	struct FGeneratedDataAssetInfo
	{
		UDataAsset* DataAsset = nullptr;
		FString UniqueId;
		FString BakeFolder;
		FString BakeOutputName;
	};

	static bool IsObjectReferenceProperty(FProperty* Property);
	static void NormalizeDataAssetPropertyNamesInJsonObject(UClass* DataAssetClass, const TSharedPtr<FJsonObject>& JsonObject);
	static bool ResolveDataAssetReferencesInJsonObject(
		UClass* DataAssetClass,
		const TSharedPtr<FJsonObject>& JsonObject,
		UDataAsset* RootDataAsset,
		const FHoudiniPackageParams& PackageParams,
		TMap<FString, FGeneratedDataAssetInfo>& GeneratedDataAssets);
	static bool ResolveDataAssetReferenceJsonValue(
		FProperty* Property,
		TSharedPtr<FJsonValue>& JsonValue,
		UDataAsset* RootDataAsset,
		const FHoudiniPackageParams& PackageParams,
		TMap<FString, FGeneratedDataAssetInfo>& GeneratedDataAssets);
	static UDataAsset* CreateNestedDataAsset(
		const TSharedPtr<FJsonObject>& JsonObject,
		UDataAsset* RootDataAsset,
		const FHoudiniPackageParams& PackageParams,
		TMap<FString, FGeneratedDataAssetInfo>& GeneratedDataAssets);
	static bool BuildDataAssetsFromPointAttributes(
		const FHoudiniGeoPartObject& HGPO,
		UHoudiniOutput* CurOutput,
		const FHoudiniPackageParams& PackageParams);

	// Applies one compatible point attribute to an editable Data Asset property. Missing or incompatible
	// attributes return false so the caller preserves the property's class default value.
	static bool ApplyPointPropertyAttribute(
		const FHoudiniGeoPartObject& HGPO,
		FProperty* Property,
		void* ValuePtr,
		const FString& AttributeName,
		int32 PointIndex = 0,
		const TArray<UDataAsset*>* PointDataAssets = nullptr);
};
